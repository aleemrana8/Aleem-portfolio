const ICON_KEYS = Object.keys(TECH_ICONS);

interface FloatingIcon {
  id: number;
  icon: string;
  x: number;       // start x %
  y: number;       // start y %
  size: number;    // px
  opacity: number;
  duration: number; // seconds for full drift
  delay: number;
  driftX: number;  // px drift
  driftY: number;
  rotation: number;
}

function generateIcons(count: number): FloatingIcon[] {
  const icons: FloatingIcon[] = [];
  for (let i = 0; i < count; i++) {
    icons.push({
      id: i,
      icon: ICON_KEYS[i % ICON_KEYS.length],
      x: Math.random() * 100,
      y: Math.random() * 100,
      size: 16 + Math.random() * 20,
      opacity: 0.03 + Math.random() * 0.05,
      duration: 25 + Math.random() * 35,
      delay: -Math.random() * 30,
      driftX: (Math.random() - 0.5) * 120,
      driftY: (Math.random() - 0.5) * 80,
      rotation: Math.random() * 360,
    });
  }
  return icons;
}

const FloatingIcon = memo(function FloatingIcon({ icon }: { icon: FloatingIcon }) {
  const tech = TECH_ICONS[icon.icon];
  if (!tech) return null;

  return (
    <motion.div
      className="absolute pointer-events-none select-none"
      style={{
        left: `${icon.x}%`,
        top: `${icon.y}%`,
        width: icon.size,
        height: icon.size,
      }}
      initial={{
        opacity: 0,
        x: 0,
        y: 0,
        rotate: icon.rotation,
        filter: "blur(1px)",
      }}
      animate={{
        opacity: [0, icon.opacity, icon.opacity, 0],
        x: [0, icon.driftX * 0.3, icon.driftX * 0.7, icon.driftX],
        y: [0, icon.driftY * 0.3, icon.driftY * 0.7, icon.driftY],
        rotate: [icon.rotation, icon.rotation + 40, icon.rotation + 80, icon.rotation + 120],
      }}
      transition={{
        duration: icon.duration,
        repeat: Infinity,
        delay: icon.delay,
        ease: "linear",
      }}
    >
      <svg
        viewBox="0 0 24 24"
        fill="none"
        className="w-full h-full"
        style={{ filter: `blur(0.5px) drop-shadow(0 0 4px rgba(56,189,248,0.15))` }}
      >
        <path d={tech.path} fill="rgba(56,189,248,0.6)" />
      </svg>
    </motion.div>
  );
});

/**
 * Renders floating tech icons across the entire viewport.
 * Fixed position, pointer-events-none, sits behind content.
 */
export const FloatingTechIcons = memo(function FloatingTechIcons({
  count = 30,
}: {
  count?: number;
}) {
  const icons = useMemo(() => generateIcons(count), [count]);

  return (
    <div
      className="fixed inset-0 z-[1] pointer-events-none overflow-hidden"
      aria-hidden="true"
    >
      {icons.map((icon) => (
        <FloatingIcon key={icon.id} icon={icon} />
      ))}
    </div>
  );
});

export default FloatingTechIcons;
